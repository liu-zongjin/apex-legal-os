'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync('frontend/personal-vault.js', 'utf8');
const sandbox = vm.createContext({ URL });
vm.runInContext(source + ';this.recognize = vaultRecognize;this.safeUrl = vaultSafeUrl;', sandbox);
function parse(text) { return JSON.parse(JSON.stringify(sandbox.recognize(text))); }
let result = parse('网址：https://example.test\n账号：sample-user\n密码：sample-secret');
assert.deepStrictEqual(result.values, {account:'sample-user', password:'sample-secret', site:'https://example.test', url:'https://example.test'});
result = parse('账号为sample-user，密码是sample-secret，平台：示例应用');
assert.deepStrictEqual(result.values, {account:'sample-user', password:'sample-secret', site:'示例应用', url:''});
result = parse('账号：first\n账号：second\n密码：sample-secret');
assert.strictEqual(result.values.account, '');
assert.deepStrictEqual(result.ambiguous, ['account']);
assert.strictEqual(result.values.password, 'sample-secret');
result = parse('联系 sample@example.test，密码：sample-secret');
assert.strictEqual(result.values.account, 'sample@example.test');
assert.strictEqual(parse('无标签的不确定内容').values.password, '');
assert.strictEqual(parse('密码：alpha,beta;gamma').values.password, 'alpha,beta;gamma');
result = parse('账号：\n密码：sample-secret');
assert.strictEqual(result.values.account, '');
assert.strictEqual(result.values.password, 'sample-secret');
result = parse('**用户名：** demo.user\n**密码：** 6#r!9\n**网址：** https://example.test');
assert.strictEqual(result.values.account, 'demo.user');
assert.strictEqual(result.values.password, '6#r!9');
assert.strictEqual(result.values.url, 'https://example.test');
result = parse('账号 demo 密码 Qx!34\nAPP 企业助手\n网址 https://example.test');
assert.deepStrictEqual(result.values, {account:'demo', password:'Qx!34', site:'企业助手', url:'https://example.test'});
result = parse('请使用登录账号是测试员，登录密码为P@55word，登录网址：https://example.test');
assert.strictEqual(result.values.account, '测试员');
assert.strictEqual(result.values.password, 'P@55word');
result = parse('账号\ncase-user\n密码\np@ss-word');
assert.strictEqual(result.values.account, 'case-user');
assert.strictEqual(result.values.password, 'p@ss-word');
result = parse('test-account\nP@ss-example');
assert.strictEqual(result.values.account, 'test-account');
assert.strictEqual(result.values.password, 'P@ss-example');
assert.strictEqual(result.inferred, true);
result = parse('one\ntwo\nthree');
assert.strictEqual(result.values.account, '');
assert.strictEqual(result.values.password, '');
assert.strictEqual(result.inferred, false);
assert.strictEqual(sandbox.safeUrl('https://example.test/path'), 'https://example.test/path');
assert.strictEqual(sandbox.safeUrl('javascript:alert(1)'), '');
assert.strictEqual(sandbox.safeUrl('https://user:pass@example.test/'), '');
sandbox.window = { location: { href: '' } };
sandbox.isNativeShell = () => true;
vm.runInContext("vault.items = [{id:'synthetic',site:'Example',url:'https://example.test/login'}];vaultOpenUrl('synthetic')", sandbox);
assert.strictEqual(sandbox.window.location.href, 'legalkb-external://open?url=https%3A%2F%2Fexample.test%2Flogin');
console.log('Vault local recognition checks passed');
